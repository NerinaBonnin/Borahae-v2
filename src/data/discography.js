/**
 * Renderiza la lista de álbumes según el filtro de categoría y búsqueda
 */
function renderDiscographyGrid() {
    const container = document.getElementById('discography-grid');
    if (!container) return; // Validación por si el contenedor no está en el DOM actual

    // Filtrar datos
    const filteredAlbums = albumsData.filter(album => {
    const matchesCategory = (currentCategory === 'all') || (album.type === currentCategory);
    const matchesSearch = album.title.toLowerCase().includes(currentSearchTerm.toLowerCase());
    return matchesCategory && matchesSearch;
    });

    // Limpiar contenedor
    container.innerHTML = '';

    if (filteredAlbums.length === 0) {
        container.innerHTML = `<p class="no-results">No se encontraron lanzamientos.</p>`;
        return;
    }

    // Generar HTML de cada card
    filteredAlbums.forEach(album => {
    const card = document.createElement('div');
    card.classList.add('album-card');
    card.dataset.id = album.id;
    card.innerHTML = `
        <div class="album-cover-container">
        <img src="${album.cover}" alt="${album.title}" class="album-cover" loading="lazy">
        <button class="view-tracks-btn" data-id="${album.id}">Ver Canciones</button>
        </div>
        <div class="album-info">
        <h3 class="album-title">${album.title}</h3>
        <span class="album-type">${album.type.toUpperCase()}</span>
        <span class="album-date">${new Date(album.releaseDate).getFullYear()}</span>
        </div>
    `;
    container.appendChild(card);
    });

        // Re-vincular eventos de los botones recién creados
    attachAlbumCardEvents();
}

function attachAlbumCardEvents() {
    const trackButtons = document.querySelectorAll('.view-tracks-btn');
    trackButtons.forEach(button => {
        button.addEventListener('click', (e) => {
            const albumId = e.target.dataset.id;
            openAlbumModal(albumId);
        });
    });
}

// --- MANEJO DE MODAL / DETALLES DE ÁLBUM ---

function openAlbumModal(albumId) {
    const album = albumsData.find(item => item.id === albumId);
    const modal = document.getElementById('album-modal');
    const modalContent = document.getElementById('album-modal-details');
    
    if (!album || !modal || !modalContent) return;
    const tracksHTML = album.tracks.map(track => `
        <li class="track-item">
        <span class="track-num">${track.number}.</span>
        <span class="track-title">${track.title}</span>
        <span class="track-duration">${track.duration}</span>
        </li>
    `).join('');

    modalContent.innerHTML = `
    <div class="modal-album-header">
    <img src="${album.cover}" alt="${album.title}">
    <div>
        <h2>${album.title}</h2>
        <p>${album.type.toUpperCase()} • ${album.releaseDate}</p>
    </div>
    </div>
    <ul class="tracklist">
        ${tracksHTML}
    </ul>
    `;

    modal.classList.add('active');
}

/**
 * Cierra el modal de álbumes
 */
function closeAlbumModal() {
    const modal = document.getElementById('album-modal');
    if (modal) {
        modal.classList.remove('active');
    }
}

// --- INICIALIZACIÓN Y EVENT LISTENERS ---

document.addEventListener('DOMContentLoaded', () => {
    // Inicializar grilla de discografía
    renderDiscographyGrid();

    // Listeners para los botones de categoría (All, Albums, Singles)
    const filterButtons = document.querySelectorAll('.filter-btn');
    filterButtons.forEach(btn => {
        btn.addEventListener('click', (e) => {
            filterButtons.forEach(b => b.classList.remove('active'));
            e.target.classList.add('active');
            currentCategory = e.target.dataset.category || 'all';
            renderDiscographyGrid();
        });
    });

    // Listener para la barra de búsqueda de discografía
    const searchInput = document.getElementById('discography-search');
    if (searchInput) {
        searchInput.addEventListener('input', (e) => {
        currentSearchTerm = e.target.value;
        renderDiscographyGrid();
        });
    }

    // Listener para cerrar modal
    const closeModalBtn = document.getElementById('close-modal-btn');
    if (closeModalBtn) {
        closeModalBtn.addEventListener('click', closeAlbumModal);
    }
});
